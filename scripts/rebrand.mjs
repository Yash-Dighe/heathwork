#!/usr/bin/env node
/* rebrand.mjs — apply brand.json to the codebase. Idempotent and re-runnable:
   the last applied brand is recorded in .brand-applied.json, so changing the name
   in brand.json and re-running replaces the previous name everywhere it was applied.

   What it touches:
   - display names: whole-word "StarNet"/"STARNET" (or the previously applied name) in runtime
     code, tests and top-level docs. Identifiers are left alone on purpose: env vars
     (STARNET_*), compound symbols (StarNetNative), storage keys ('starnet.*').
   - the desktop identity: tauri productName/identifier, keychain service, data-dir name.
   - frontend/app/brand.js: the generated BRAND object the UI reads URLs from.
   - the updater endpoint (or a disabled placeholder when urls.updaterEndpoint is empty). */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const brand = JSON.parse(fs.readFileSync(path.join(ROOT, 'brand.json'), 'utf8'));
const APPLIED = path.join(ROOT, '.brand-applied.json');
const prev = fs.existsSync(APPLIED)
  ? JSON.parse(fs.readFileSync(APPLIED, 'utf8'))
  : { name: 'StarNet', nameUpper: 'STARNET', identifier: 'ai.skynet.harness', aliases: ['Starnet'] };

const SCOPES = ['frontend', 'sidecar', 'shared', 'test', 'src-tauri/src', 'scripts', '.github/workflows'];
// Legal/project docs (README, PRIVACY, TERMS, SECURITY, INSTALL) are yours to write, not to find-and-replace.
const TOP_FILES = ['package.json', 'src-tauri/Cargo.toml', 'src-tauri/tauri.conf.json'];
const EXT = new Set(['.js', '.mjs', '.cjs', '.json', '.html', '.css', '.md', '.rs', '.toml', '.txt', '.svg', '.sh', '.ps1', '.yml', '.yaml']);
const SKIP_DIRS = new Set(['node_modules', '.git', 'assets', 'target', 'frontend-dist']);

const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const word = s => new RegExp('(?<![A-Za-z0-9_]|X-)' + esc(s) + '(?![A-Za-z0-9_])', 'g');
const rules = [];
if (prev.name !== brand.name) rules.push([word(prev.name), brand.name]);
for (const a of prev.aliases || []) if (a !== brand.name) rules.push([word(a), brand.name]);
// The upper-case name doubles as the env-var namespace (STARNET_*). Never rewrite it inside a regex
// alternation like /^(?:STARNET|SKYNET)_/ — that is matching env names, not showing a name.
if (prev.nameUpper !== brand.nameUpper) rules.push([new RegExp('(?<![A-Za-z0-9_|:])' + esc(prev.nameUpper) + '(?![A-Za-z0-9_|)])', 'g'), brand.nameUpper]);
if (prev.identifier !== brand.identifier) {
  rules.push([new RegExp(esc(prev.identifier), 'g'), brand.identifier]);
  // the same identifier written inside a regex literal (tests assert on it as /ai\.skynet\.harness/)
  rules.push([new RegExp(esc(esc(prev.identifier)), 'g'), esc(brand.identifier)]);
}

function* walk(dir) {
  if (!fs.existsSync(dir)) return;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) yield* walk(p);
    else if (EXT.has(path.extname(e.name))) yield p;
  }
}

let changed = 0;
const files = [...SCOPES.flatMap(s => [...walk(path.join(ROOT, s))]), ...TOP_FILES.map(f => path.join(ROOT, f))];
for (const f of files) {
  if (!fs.existsSync(f) || f.endsWith('rebrand.mjs') || f.endsWith('brand.json') || f.endsWith(path.join('app', 'brand.js'))) continue;
  const before = fs.readFileSync(f, 'utf8');
  let after = before;
  for (const [re, to] of rules) after = after.replace(re, to);
  if (after !== before) { fs.writeFileSync(f, after); changed++; }
}

// Desktop identity + updater
const confPath = path.join(ROOT, 'src-tauri', 'tauri.conf.json');
const conf = JSON.parse(fs.readFileSync(confPath, 'utf8'));
conf.productName = brand.name;
conf.identifier = brand.identifier;
if (conf.app && Array.isArray(conf.app.windows)) for (const w of conf.app.windows) if (w.title) w.title = brand.name;
const upd = conf.plugins && conf.plugins.updater;
if (upd) {
  upd.endpoints = brand.urls.updaterEndpoint ? [brand.urls.updaterEndpoint] : ['https://updates.invalid/disabled/latest.json'];
  if (!brand.urls.updaterEndpoint) upd.pubkey = 'REPLACE_WITH_YOUR_TAURI_UPDATER_PUBKEY';
}
fs.writeFileSync(confPath, JSON.stringify(conf, null, 2) + '\n');

// Frontend BRAND object
const brandJs = `/* GENERATED by scripts/rebrand.mjs from brand.json — do not edit by hand. */
'use strict';
const BRAND = Object.freeze(${JSON.stringify({ name: brand.name, nameUpper: brand.nameUpper,
  tagline: brand.tagline, urls: brand.urls }, null, 2)});
if (typeof window !== 'undefined') window.BRAND = BRAND;
`;
fs.writeFileSync(path.join(ROOT, 'frontend', 'app', 'brand.js'), brandJs);
// The sidecar reads shared/brand.json (shared/ ships inside the desktop bundle; the repo root does not).
fs.writeFileSync(path.join(ROOT, 'shared', 'brand.json'), JSON.stringify(brand, null, 2) + '\n');

fs.writeFileSync(APPLIED, JSON.stringify({ name: brand.name, nameUpper: brand.nameUpper, identifier: brand.identifier }, null, 2) + '\n');
// regenerate the wordmark/logo for the (possibly new) name
await import('./make-wordmark.mjs');
console.log(`rebrand: ${prev.name} -> ${brand.name}; ${changed} files rewritten; tauri identity + frontend/app/brand.js updated`);
